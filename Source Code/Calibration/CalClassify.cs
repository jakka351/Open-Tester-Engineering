//
//  CalClassify.cs — keyword classifiers used to (a) flag the safety/legal risk class of a
//  table (so the editor can colour it and double-confirm dangerous edits) and (b) build a
//  sensible category tree when the definition file doesn't carry one (A2L FUNCTIONs are
//  optional; many XDFs are flat).  Pure heuristics over the table's name/title/units — they
//  only ever *add* a hint, never block bench editing.
// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
using System;
using System.Linq;

namespace TesterPresent.OBD2.Calibration
{
    public static class CalRisk
    {
        private static readonly string[] Emissions =
        {
            "CAT", "CATALYST", "O2", "LAMBDA", "EGR", "DPF", "GPF", "SCR", "ADBLUE", "UREA",
            "EVAP", "PURGE", "NOX", "READINESS", "SEC AIR", "SECONDARY AIR", "EMISSION",
            "OBD", "MONITOR", "CLOSED LOOP", "FUEL TRIM"
        };
        private static readonly string[] Safety =
        {
            "TORQUE LIMIT", "TQ LIMIT", "REV LIMIT", "RPM LIMIT", "SPEED LIMIT", "LIMITER",
            "OVERBOOST", "OVER BOOST", "ABS", "AIRBAG", "SRS", "RESTRAINT", "ESP", "ESC",
            "TRACTION", "BRAKE", "STEERING", "IMMOBIL", "CLUTCH PROTECT", "OVERSPEED",
            "MAX TORQUE", "TORQUE MONITOR", "MONITORING"
        };

        public static CalRiskClass Classify(params string[] fields)
        {
            string hay = " " + string.Join(" ", (fields ?? Array.Empty<string>()).Where(s => !string.IsNullOrEmpty(s)))
                                       .ToUpperInvariant() + " ";
            if (Safety.Any(k => hay.Contains(k)))    return CalRiskClass.Safety;
            if (Emissions.Any(k => hay.Contains(k))) return CalRiskClass.Emissions;
            return CalRiskClass.Normal;
        }
    }

    public static class CalCategoriser
    {
        // (keyword, category) — first match wins; gives a clean tree without a definition's help.
        private static readonly (string kw, string cat)[] Rules =
        {
            ("SPARK","Ignition"), ("IGNITION","Ignition"), ("TIMING","Ignition"), ("KNOCK","Ignition"), ("DWELL","Ignition"),
            ("INJECT","Fuel"), ("FUEL","Fuel"), (" VE","Fuel"), ("VOLUMETRIC","Fuel"), ("LAMBDA","Fuel"), ("AFR","Fuel"), ("PULSE","Fuel"), ("RAIL","Fuel"),
            ("BOOST","Boost"), ("WASTEGATE","Boost"), ("TURBO","Boost"), ("VGT","Boost"), ("CHARGE","Boost"), ("WG ","Boost"),
            ("IDLE","Idle"),
            ("LIMIT","Limits"), ("LIMITER","Limits"), ("CLIP","Limits"), ("MAX ","Limits"), ("PROTECT","Limits"),
            ("GEAR","Transmission"), ("SHIFT","Transmission"), ("TRANS","Transmission"), ("CLUTCH","Transmission"), ("CONVERTER","Transmission"), ("TCC","Transmission"),
            ("THROTTLE","Throttle"), ("PEDAL","Throttle"), ("ETC","Throttle"), ("DBW","Throttle"), ("TPS","Throttle"),
            ("CAM","Cam / VVT"), ("VVT","Cam / VVT"), ("VANOS","Cam / VVT"), ("PHASE","Cam / VVT"), ("VCT","Cam / VVT"),
            ("MAF","Sensors"), ("MAP ","Sensors"), ("IAT","Sensors"), ("ECT","Sensors"), ("SENSOR","Sensors"), ("TEMP","Sensors"),
            ("CAT","Emissions"), ("EGR","Emissions"), ("DPF","Emissions"), ("O2","Emissions"), ("EVAP","Emissions"), ("PURGE","Emissions"),
            ("TORQUE","Torque"), ("TQ ","Torque"),
            ("CRANK","Starting"), ("START","Starting"), ("PRIME","Starting"),
        };

        /// <summary>If a table has no category from its definition, assign one by keyword.</summary>
        public static void Assign(CalTable tbl)
        {
            if (tbl.Categories.Count > 0) return;
            string hay = " " + (tbl.Name + " " + tbl.Title).ToUpperInvariant() + " ";
            foreach (var (kw, cat) in Rules)
                if (hay.Contains(kw)) { tbl.Categories.Add(cat); return; }
            tbl.Categories.Add(tbl.Risk == CalRiskClass.Emissions ? "Emissions" : "General");
        }
    }
}
