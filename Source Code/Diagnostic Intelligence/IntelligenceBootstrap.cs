// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Tester Present Specialist Automotive Solutions — Diagnostic Intelligence Bootstrap
//
//  One-shot registration of the built-in platform calibrations into the
//  CalibrationRegistry.  Call EnsureRegistered() before resolving a calibration
//  (the module runner and the UI host both call it; it is idempotent and cheap).
//
//  Keeping this outside Core avoids any compile-time dependency from the Core
//  contracts on the concrete calibration classes.
// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
using System.Threading;
using TesterPresent.OBD2.Intelligence.Stores;

namespace TesterPresent.OBD2.Intelligence
{
    public static class IntelligenceBootstrap
    {
        private static readonly object _gate = new object();
        private static volatile bool _done;
        private static CalibrationStore _calStore;

        /// <summary>Register built-in calibrations exactly once. Idempotent, thread-safe.</summary>
        public static void EnsureRegistered()
        {
            if (_done) return;            // fast path once registration has completed
            lock (_gate)
            {
                if (_done) return;

                CalibrationRegistry.Register(
                    matches: (oem, vin) => FordFgCalibration.Matches(oem, vin),
                    create: () => new FordFgCalibration(),
                    priority: 100);

                CalibrationRegistry.RegisterFallback(() => new GenericCalibration());

                // Field-validated overrides: overlay the JSON calibration store on top of the
                // spec-seeded base so a bench-characterised platform can promote its findings
                // out of advisory (a validated key reads validated=true). Empty store ⇒ no-op.
                _calStore = new CalibrationStore();
                CalibrationRegistry.SetOverlay(baseCal =>
                {
                    try
                    {
                        if (baseCal == null || !_calStore.HasPlatform(baseCal.PlatformId)) return baseCal;
                        return new DbBackedPlatformCalibration(baseCal, _calStore.GetPlatform(baseCal.PlatformId));
                    }
                    catch { return baseCal; }
                });

                // Publish the done-flag only AFTER the registrations are in place.  The old
                // Interlocked.Exchange set the flag FIRST, so a second thread could see
                // "done" and resolve a calibration against a still-empty registry.
                _done = true;
            }
        }

        /// <summary>The shared field-validated calibration store (null until EnsureRegistered).</summary>
        public static CalibrationStore CalibrationStore => _calStore;
    }
}
