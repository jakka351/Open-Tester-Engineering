// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Tester Present Specialist Automotive Solutions — The Investigation Tree (Diagnostic Session)
//
//  The SPINE of Diagnostic Intelligence: a live, branching, backtracking
//  investigation graph that grows from the instant the tech hits CONNECT and is
//  never precomputed.  It is the mechanic's own mental model made literal —
//  CONNECT is the root, VIN/topology/DTC readouts fan the first branches,
//  hypotheses are competing branches, tests are gated edges, and FAILURE is a
//  first-class outcome that flips a node's status (Live → Refuted/Suspended/Pruned)
//  but NEVER deletes it, so the ruled-out branches ARE the map of where you've been.
//
//  Two projections of ONE node set: the FRONTIER (which theories are still live) is
//  Live hypotheses ordered by belief; the PROVENANCE graph is the same set including
//  the greyed-out dead ends.  M6's Bayesian ranking (RankedFault) seeds the frontier;
//  the tree accumulates per-fault log-odds deltas from the OUTCOMES of tests the tech
//  actually ran — applied ONCE, kept DISJOINT from the snapshot evidence M6 derives
//  from, so nothing is double-counted.
//
//  HONESTY (non-negotiable): the tech-facing surface binds to the coarse BAND, never
//  a percentage; no hypothesis becomes BestSupported without an INDEPENDENT confirming
//  test that ACTUALLY RAN on the connected vehicle; a volatile/intermittent hypothesis
//  cannot be refuted on one clean pass; and the residual is triaged, never silently
//  cleared.  The tool PROPOSES; the tech CONFIRMS.
// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
using System;
using System.Collections.Generic;
using System.Linq;

namespace TesterPresent.OBD2.Intelligence.Session
{
    /// <summary>What a node in the investigation graph is.</summary>
    public enum NodeKind { Root, Observation, Hypothesis, Test, Outcome, Fix }

    /// <summary>A node's place in the live/ruled-out projection. NO "Confirmed" — the
    /// honest terminal is BestSupported (survived every test that ran on this car).</summary>
    public enum NodeStatus { Live, BestSupported, Refuted, Suspended, Pruned }

    /// <summary>The relationship an edge encodes. Supports carries a signed delta (a
    /// negative delta IS a refutation), so there is no separate Refutes kind.</summary>
    public enum EdgeKind { Establishes, Discriminates, Ruled, Supports, Fixes }

    /// <summary>One node of the investigation graph.</summary>
    public sealed class ReasoningNode
    {
        public Guid Id { get; set; } = Guid.NewGuid();
        public NodeKind Kind { get; set; }
        public Guid? ParentId { get; set; }
        public string Title { get; set; } = "";
        public DateTime CreatedUtc { get; set; } = DateTime.UtcNow;
        public NodeStatus Status { get; set; } = NodeStatus.Live;
        public EvidenceChain Evidence { get; set; }
        /// <summary>Where this node came from: "M6", "tool:CanBusHealth", "Human", "procedure:…".</summary>
        public string Source { get; set; } = "";

        // ── Hypothesis payload ──
        public string FaultKey { get; set; }
        public FaultBand Band { get; set; }
        /// <summary>Belief from M6's snapshot ranking (recomputed each engine run).</summary>
        public double BaseLogOdds { get; set; }
        /// <summary>Belief accumulated from the OUTCOMES of tests the tech ran (applied once).</summary>
        public double AccumulatedDelta { get; set; }
        public bool PriorFromHistory { get; set; }
        /// <summary>Intermittent / lost-comms fault: cannot be refuted on one clean pass.</summary>
        public bool Volatile { get; set; }
        /// <summary>How many times a clean test has failed to reproduce a volatile fault.</summary>
        public int RefuteAttempts { get; set; }
        /// <summary>Set once an INDEPENDENT test that ran on the vehicle confirmed this fault
        /// — the gate between Live and BestSupported.</summary>
        public bool ConfirmedOnVehicle { get; set; }
        public List<string> Suspects { get; set; } = new List<string>();

        // ── Outcome payload ──
        public EvidenceVerdict Verdict { get; set; }

        // ── Fix payload (E4) ──
        /// <summary>The concrete repair action a Fix node proposes (procedure name) — the key that
        /// feeds repair-history learning (E3) when the fix outcome is recorded.</summary>
        public string FixAction { get; set; }

        // ── Internal ranking (never tech-facing) ──
        public double EffectiveLogOdds => BaseLogOdds + AccumulatedDelta;
        public double EffectivePosterior => Logistic.Sigmoid(EffectiveLogOdds);
    }

    /// <summary>An edge between two nodes. LogOddsDelta is the actual signed Bayesian weight
    /// applied — provenance is the arithmetic, not a label.</summary>
    public sealed class Edge
    {
        public Guid FromId { get; set; }
        public Guid ToId { get; set; }
        public EdgeKind Kind { get; set; }
        public double LogOddsDelta { get; set; }
        public string Rationale { get; set; } = "";
    }

    /// <summary>The single most-discriminating next test the tree proposes (tech decides to run it).</summary>
    public sealed class TestProposal
    {
        public Guid TestNodeId { get; set; }
        public string Title { get; set; }
        public string DiscriminatingText { get; set; }
        public string LeadingFaultKey { get; set; }
        public string ContenderFaultKey { get; set; }
    }

    /// <summary>Small logistic helpers (mirror M6's Logit/Sigmoid, kept local so the session
    /// is self-contained and the module stays private).</summary>
    internal static class Logistic
    {
        public static double Sigmoid(double x) => 1.0 / (1.0 + Math.Exp(-x));
        public static double Logit(double p)
        {
            p = p < 1e-6 ? 1e-6 : (p > 1 - 1e-6 ? 1 - 1e-6 : p);
            return Math.Log(p / (1 - p));
        }
    }

    /// <summary>
    /// The live investigation graph for one vehicle session. Host-side (holds no I/O);
    /// it is fed engine runs + test outcomes and projects the frontier + the trodden map.
    /// </summary>
    public sealed class DiagnosticSession
    {
        // Tuning (spec-seeded; the rings-true bar is [RequiresValidation] until calibrated on real faults).
        private const double PRUNE_FLOOR_POSTERIOR = 0.05;   // effective posterior below this ⇒ pruned (kept on map)
        private const double STRONG_REFUTE_DELTA   = 1.5;    // a discriminating outcome this strong is a definitive refute
        private const int    VOLATILE_REFUTE_MIN   = 2;      // clean passes needed before a volatile fault may be refuted

        public string Vin { get; set; } = "";
        public string Platform { get; set; } = "";
        public int ModelYear { get; set; }
        public DateTime ConnectedUtc { get; set; } = DateTime.UtcNow;
        public Guid RootId { get; set; }
        public List<ReasoningNode> Nodes { get; set; } = new List<ReasoningNode>();
        public List<Edge> Edges { get; set; } = new List<Edge>();

        /// <summary>The discriminating text M6 attached to its leader on the last engine run.</summary>
        public string LastDiscriminator { get; set; }

        // ── Lifecycle ──────────────────────────────────────────────────────────

        public DiagnosticSession() { }

        /// <summary>Start a new session at CONNECT — the root of the tree.</summary>
        public static DiagnosticSession Start(string vin, string platform = null, int modelYear = 0)
        {
            var s = new DiagnosticSession { Vin = vin ?? "", Platform = platform ?? "", ModelYear = modelYear };
            var root = new ReasoningNode { Kind = NodeKind.Root, Title = "Connected to vehicle", Source = "session" };
            s.RootId = root.Id;
            s.Nodes.Add(root);
            return s;
        }

        public ReasoningNode Node(Guid id) => Nodes.FirstOrDefault(n => n.Id == id);

        // ── Growth: observations fan the opening branches ───────────────────────

        /// <summary>Append an evidence Observation (VIN decode, a module, a DTC, a captured signal).
        /// Returns the new node id.</summary>
        public Guid AppendObservation(string title, EvidenceChain ev = null, Guid? parent = null, string source = "capture")
        {
            var n = new ReasoningNode
            {
                Kind = NodeKind.Observation,
                Title = title,
                Evidence = ev,
                Source = source,
                ParentId = parent ?? RootId,
            };
            Nodes.Add(n);
            AddEdge(n.ParentId.Value, n.Id, EdgeKind.Establishes, 0, "observation recorded");
            return n.Id;
        }

        // ── Growth: hypotheses are competing branches (seeded from M6's frontier) ─

        /// <summary>
        /// Upsert one Hypothesis node per RankedFault in the engine run, keyed by FaultKey.
        /// Snapshot-derived belief lands on <see cref="ReasoningNode.BaseLogOdds"/>; the tree's
        /// own <see cref="ReasoningNode.AccumulatedDelta"/> (from test outcomes) and the node
        /// Status are PRESERVED — a refuted branch stays refuted, the failures stay on the map.
        /// The M6 posterior is DISJOINT from the outcome deltas, so nothing is double-counted.
        /// </summary>
        public void SpawnHypotheses(DiagnosticRunResult run, IEnumerable<Guid> fromObservations = null)
        {
            if (run?.RankedFaults == null) return;
            var obsIds = fromObservations?.ToList() ?? new List<Guid>();

            // Carry the discriminating test M6 chose for its leader (the value-of-information move).
            var m6 = run.Results?.FirstOrDefault(r => r.ModuleId == "M6" && r.RankedFaults != null);
            if (m6 != null && !string.IsNullOrEmpty(m6.NextTest)) LastDiscriminator = m6.NextTest;

            foreach (var rf in run.RankedFaults)
            {
                // A hypothesis branch must be a real FAULT, not M6's free-form fallback for an
                // unmapped module result — those "FF:" candidates are Info/data-availability
                // notes ("… unavailable at this data rate"), never a fault to chase. Skip them.
                if (rf.FaultKey == null || rf.FaultKey.StartsWith("FF:", StringComparison.OrdinalIgnoreCase)) continue;

                var node = Nodes.FirstOrDefault(n => n.Kind == NodeKind.Hypothesis
                    && string.Equals(n.FaultKey, rf.FaultKey, StringComparison.OrdinalIgnoreCase));
                if (node == null)
                {
                    node = new ReasoningNode
                    {
                        Kind = NodeKind.Hypothesis,
                        FaultKey = rf.FaultKey,
                        Title = rf.Label,
                        Source = "M6",
                        ParentId = RootId,
                        // Per-scan volatility from THIS run's DTC grammar (rf.Volatile) OR an
                        // intrinsically-volatile fault class — never a process-global key lookup.
                        Volatile = rf.Volatile || IsVolatileFault(rf.FaultKey),
                    };
                    Nodes.Add(node);
                    // Establishing edges ONLY from the DTC observations that ACTUALLY raised this
                    // hypothesis — i.e. whose code appears in the fault's evidence.  Linking every
                    // DTC to every hypothesis (the old behaviour) blinded TriageResidual: a DTC that
                    // spawned no hypothesis (a lone U-code M6 didn't rank) must stay UNLINKED so it
                    // surfaces as unexplained residual instead of being silently "covered".
                    var raisedByCodes = DtcCodesOf(rf);
                    foreach (var o in obsIds)
                    {
                        var obs = Node(o);
                        // A DTC observation carries its code on FaultKey (set by the orchestrator);
                        // link only the genuine raiser. A fault raised purely by live signals (no DTC
                        // in its evidence) links no DTC — correct: no DTC established it.
                        if (obs != null && raisedByCodes.Count > 0
                            && obs.FaultKey != null && raisedByCodes.Contains(obs.FaultKey))
                            AddEdge(o, node.Id, EdgeKind.Establishes, 0, "raised by DTC " + obs.FaultKey);
                    }
                }
                // Refresh snapshot-derived belief + provenance; PRESERVE Status + AccumulatedDelta.
                node.BaseLogOdds = rf.LogOdds;
                node.PriorFromHistory = rf.PriorFromHistory;
                if (rf.Suspects != null)
                    foreach (var sc in rf.Suspects) if (!node.Suspects.Contains(sc)) node.Suspects.Add(sc);
            }

            RecomputeBands();
        }

        // ── The tech drives: propose the single most-discriminating next test ────

        /// <summary>
        /// Propose the one test that best separates the top two LIVE hypotheses (M6's
        /// value-of-information move). Creates a Test node with Discriminates edges from both.
        /// Returns null when there is nothing left to discriminate (0 or 1 live hypothesis).
        /// </summary>
        public TestProposal ProposeNextTest()
        {
            var live = Frontier();
            if (live.Count == 0) return null;
            var leader = live[0];
            var contender = live.Count > 1 ? live[1] : null;

            var test = new ReasoningNode
            {
                Kind = NodeKind.Test,
                Title = contender != null
                    ? $"Discriminate: {leader.Title} vs {contender.Title}"
                    : $"Confirm: {leader.Title}",
                Source = "M6",
                ParentId = leader.Id,
            };
            Nodes.Add(test);
            AddEdge(leader.Id, test.Id, EdgeKind.Discriminates, 0, "leading hypothesis under test");
            if (contender != null) AddEdge(contender.Id, test.Id, EdgeKind.Discriminates, 0, "contending hypothesis under test");

            return new TestProposal
            {
                TestNodeId = test.Id,
                Title = test.Title,
                DiscriminatingText = LastDiscriminator ?? "Run the leading fault's confirmation and observe the result.",
                LeadingFaultKey = leader.FaultKey,
                ContenderFaultKey = contender?.FaultKey,
            };
        }

        // ── Failure prunes without forgetting; success gates on-vehicle confirmation ──

        /// <summary>
        /// Fold a test OUTCOME back into the tree. <paramref name="favouredFaultKey"/> is the
        /// hypothesis the test pointed toward (gains belief); <paramref name="refutedFaultKey"/>
        /// is the one it pointed away from (loses belief). <paramref name="strength"/> is the
        /// log-odds magnitude of the evidence. <paramref name="ranOnVehicle"/> must be true for
        /// the favoured hypothesis to ever reach BestSupported. <paramref name="independent"/>
        /// means a genuinely separate line of evidence (not a restatement of what raised it).
        /// </summary>
        public Guid ApplyOutcome(Guid testNodeId, string favouredFaultKey, string refutedFaultKey,
                                 double strength, EvidenceVerdict verdict, bool ranOnVehicle,
                                 bool independent, string summary = null, string source = "tech")
        {
            strength = Math.Abs(strength);
            var outcome = new ReasoningNode
            {
                Kind = NodeKind.Outcome,
                Title = summary ?? $"Test result: {verdict}",
                Verdict = verdict,
                Source = source,
                ParentId = testNodeId,
            };
            Nodes.Add(outcome);
            AddEdge(testNodeId, outcome.Id, EdgeKind.Ruled, 0, ranOnVehicle ? "test ran on the vehicle" : "inferred");

            // Favoured hypothesis gains belief (only an on-vehicle independent test can CONFIRM it).
            var fav = HypothesisByKey(favouredFaultKey);
            if (fav != null && verdict == EvidenceVerdict.Pass)
            {
                fav.AccumulatedDelta += strength;
                // A favouring test REVIVES a volatile fault that was Suspended after a clean pass:
                // the intermittent showed itself, so it returns to the live frontier and its clean-pass
                // counter resets. Without this a genuinely-reproduced intermittent stayed Suspended
                // forever — excluded from the frontier, unable to converge.
                if (fav.Status == NodeStatus.Suspended)
                {
                    fav.Status = NodeStatus.Live;
                    fav.RefuteAttempts = 0;
                }
                AddEdge(outcome.Id, fav.Id, EdgeKind.Supports, +strength,
                        $"{verdict}: supports {fav.Title} (+{strength:0.0#} log-odds)");
                if (ranOnVehicle && independent) fav.ConfirmedOnVehicle = true;
            }

            // Refuted hypothesis loses belief — but a VOLATILE fault survives a lone clean pass.
            var ref_ = HypothesisByKey(refutedFaultKey);
            if (ref_ != null)
            {
                if (ref_.Volatile)
                {
                    ref_.RefuteAttempts++;
                    if (ref_.RefuteAttempts < VOLATILE_REFUTE_MIN)
                    {
                        // Not reproduced this attempt — an intermittent hides when you probe it.
                        double small = Math.Min(strength, 0.5);
                        ref_.AccumulatedDelta -= small;
                        if (ref_.Status == NodeStatus.Live) ref_.Status = NodeStatus.Suspended;
                        AddEdge(outcome.Id, ref_.Id, EdgeKind.Supports, -small,
                                $"not reproduced this attempt — {ref_.Title} SUSPENDED, not ruled out (needs a wiggle-witness or repeat)");
                    }
                    else
                    {
                        ref_.AccumulatedDelta -= strength;
                        ref_.Status = NodeStatus.Refuted;
                        AddEdge(outcome.Id, ref_.Id, EdgeKind.Supports, -strength,
                                $"refuted after {ref_.RefuteAttempts} consistent clean passes (−{strength:0.0#})");
                    }
                }
                else
                {
                    ref_.AccumulatedDelta -= strength;
                    AddEdge(outcome.Id, ref_.Id, EdgeKind.Supports, -strength,
                            $"refutes {ref_.Title} (−{strength:0.0#} log-odds)");
                    if (strength >= STRONG_REFUTE_DELTA) ref_.Status = NodeStatus.Refuted;
                    else if (ref_.EffectivePosterior < PRUNE_FLOOR_POSTERIOR) ref_.Status = NodeStatus.Pruned;
                }
            }

            RecomputeBands();
            return outcome.Id;
        }

        // ── The fix arm: attach a repair to a hypothesis, then fold its outcome (E4) ──────

        /// <summary>Attach a proposed FIX to a hypothesis (NodeKind.Fix + EdgeKind.Fixes).
        /// <paramref name="fixAction"/> is the concrete repair (procedure name) that keys the
        /// repair-history learning when the outcome is recorded.</summary>
        public Guid AddFix(Guid hypothesisId, string title, string fixAction, string source = "fix")
        {
            var hyp = Node(hypothesisId);
            var fix = new ReasoningNode
            {
                Kind = NodeKind.Fix,
                Title = title,
                FixAction = fixAction,
                Source = source,
                ParentId = hypothesisId,
                FaultKey = hyp?.FaultKey,   // carry the fault key so the write-back keys correctly
            };
            Nodes.Add(fix);
            AddEdge(hypothesisId, fix.Id, EdgeKind.Fixes, 0, "proposed fix: " + (fixAction ?? title));
            return fix.Id;
        }

        /// <summary>
        /// Fold a FIX outcome. worked=true means the repair RESOLVED the complaint — the strongest
        /// possible on-vehicle confirmation, so the parent hypothesis becomes BestSupported.
        /// worked=false records a tried-but-failed fix and nudges the hypothesis down (kept Live —
        /// the fix may have been wrong even if the diagnosis is right). Returns the parent hypothesis
        /// so the orchestrator can write repair history (E3).
        /// </summary>
        public ReasoningNode ApplyFixOutcome(Guid fixNodeId, bool worked)
        {
            var fix = Node(fixNodeId);
            if (fix == null || fix.Kind != NodeKind.Fix) return null;
            fix.Verdict = worked ? EvidenceVerdict.Pass : EvidenceVerdict.Fail;

            var hyp = Node(fix.ParentId ?? Guid.Empty);
            if (hyp != null && hyp.Kind == NodeKind.Hypothesis)
            {
                if (worked)
                {
                    // A repair that resolved the complaint IS the confirmation — ground truth.
                    hyp.ConfirmedOnVehicle = true;
                    hyp.AccumulatedDelta += 2.5;
                    hyp.Status = NodeStatus.BestSupported;
                    AddEdge(fixNodeId, hyp.Id, EdgeKind.Supports, +2.5,
                            "fix resolved the complaint — confirmed on the vehicle");
                }
                else
                {
                    hyp.AccumulatedDelta -= 0.7;
                    AddEdge(fixNodeId, hyp.Id, EdgeKind.Supports, -0.7,
                            "fix did not resolve the complaint — reconsider (or the repair was incomplete)");
                }
                RecomputeBands();
            }
            return hyp;
        }

        // ── Convergence — honest: no BestSupported without an on-vehicle confirming test ──

        /// <summary>
        /// Promote the leading Live hypothesis to BestSupported IF it clearly leads AND has an
        /// independent confirming test that actually ran on the vehicle. Returns the promoted
        /// node, or null if the ConvergenceGate is not met (the honest default).
        /// </summary>
        public ReasoningNode TryConverge()
        {
            var live = Frontier();
            if (live.Count == 0) return null;
            var leader = live[0];
            bool clearlyLeads = leader.Band == FaultBand.Leading;
            if (clearlyLeads && leader.ConfirmedOnVehicle)
            {
                leader.Status = NodeStatus.BestSupported;
                return leader;
            }
            return null;
        }

        /// <summary>The honest terminal statement — never "confirmed root cause".</summary>
        public string BestSupportedSummary()
        {
            var best = Nodes.FirstOrDefault(n => n.Kind == NodeKind.Hypothesis && n.Status == NodeStatus.BestSupported);
            var residual = TriageResidual();
            string res = residual.Count == 0
                ? "no relevant residual left unexplained"
                : "still unexplained: " + string.Join(", ", residual.Select(r => r.Title));
            if (best == null)
                return "no fault has met the confirming-test bar yet — keep testing. " + res;
            return $"best-supported: {best.Title} — survived every test you ran; {res}";
        }

        /// <summary>Confirmed DTC observations not yet explained by a BestSupported / leading
        /// hypothesis — triaged, never auto-cleared (the tech dispositions each).</summary>
        public IReadOnlyList<ReasoningNode> TriageResidual()
        {
            // A DTC is "explained" only if a LIVE or BEST-SUPPORTED hypothesis establishes from it.
            // If a DTC spawned no hypothesis, or its only hypothesis was refuted/pruned, it resurfaces
            // as residual — never silently cleared. (Establishing edges are now precise per DTC, so
            // this correctly flags an unranked DTC instead of treating every DTC as covered.)
            var explainedObs = new HashSet<Guid>(
                Edges.Where(e => e.Kind == EdgeKind.Establishes)
                     .Where(e =>
                     {
                         var h = Node(e.ToId);
                         return h != null && h.Kind == NodeKind.Hypothesis
                                && (h.Status == NodeStatus.Live || h.Status == NodeStatus.BestSupported);
                     })
                     .Select(e => e.FromId));
            return Nodes.Where(n => n.Kind == NodeKind.Observation
                                    && n.Source == "dtc"
                                    && !explainedObs.Contains(n.Id)).ToList();
        }

        // ── Projections: the frontier and the trodden map are ONE node set ──────

        /// <summary>The live frontier — Live hypotheses ordered by belief. This is M6's ranking
        /// plus the outcomes of tests the tech ran.</summary>
        public IReadOnlyList<ReasoningNode> Frontier()
            => Nodes.Where(n => n.Kind == NodeKind.Hypothesis && n.Status == NodeStatus.Live)
                    .OrderByDescending(n => n.EffectivePosterior)
                    .ThenBy(n => n.Title, StringComparer.Ordinal)
                    .ToList();

        /// <summary>The ruled-out branches — kept on the map, greyed, each showing the test that killed it.</summary>
        public IReadOnlyList<ReasoningNode> RuledOut()
            => Nodes.Where(n => n.Kind == NodeKind.Hypothesis
                    && (n.Status == NodeStatus.Refuted || n.Status == NodeStatus.Pruned))
                    .ToList();

        /// <summary>Suspended (volatile, not fairly refutable on one pass) hypotheses.</summary>
        public IReadOnlyList<ReasoningNode> Suspended()
            => Nodes.Where(n => n.Kind == NodeKind.Hypothesis && n.Status == NodeStatus.Suspended).ToList();

        // ── Internals ───────────────────────────────────────────────────────────

        public void AddEdge(Guid from, Guid to, EdgeKind kind, double delta, string rationale)
            => Edges.Add(new Edge { FromId = from, ToId = to, Kind = kind, LogOddsDelta = delta, Rationale = rationale });

        private ReasoningNode HypothesisByKey(string faultKey)
            => string.IsNullOrEmpty(faultKey) ? null
             : Nodes.FirstOrDefault(n => n.Kind == NodeKind.Hypothesis
                    && string.Equals(n.FaultKey, faultKey, StringComparison.OrdinalIgnoreCase));

        /// <summary>Re-band the LIVE frontier from effective posteriors (coarse band only —
        /// never a percentage to the tech).</summary>
        private void RecomputeBands()
        {
            var live = Nodes.Where(n => n.Kind == NodeKind.Hypothesis && n.Status == NodeStatus.Live)
                            .OrderByDescending(n => n.EffectivePosterior).ToList();
            if (live.Count == 0) return;
            double sum = live.Sum(n => n.EffectivePosterior);
            var shares = live.Select(n => sum > 1e-9 ? n.EffectivePosterior / sum : 0.0).ToList();
            // live is posterior-descending; gate the leader's band on its ABSOLUTE effective
            // posterior so a lone/weak front-runner is "contending", never falsely "leading" —
            // and pass the runner-up's posterior so a leader that pulls decisively ahead can
            // band "leading" even when a big frontier dilutes every normalised share.
            var bands = FaultBanding.BandShares(shares, live[0].EffectivePosterior,
                                                live.Count > 1 ? live[1].EffectivePosterior : double.NaN);
            for (int i = 0; i < live.Count; i++) live[i].Band = bands[i];
        }

        /// <summary>The DTC codes referenced in a ranked fault's evidence (M6 Contribution.Source
        /// reads "DTC P0171 (confirmed)"). Used to link a hypothesis only to the DTC(s) that raised
        /// it, keeping TriageResidual honest.</summary>
        private static HashSet<string> DtcCodesOf(RankedFault rf)
        {
            var codes = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            if (rf?.Contributions == null) return codes;
            foreach (var c in rf.Contributions)
            {
                string s = c?.Source;
                if (string.IsNullOrEmpty(s)) continue;
                // Parse EVERY "DTC <code>" in the source — a collapsed structural contribution
                // carries the swallowed codes in its annotation ("also reported by DTC P0123 …"),
                // and each of those DTC observations must keep its Establishes link.
                int i = 0;
                while ((i = s.IndexOf("DTC ", i, StringComparison.OrdinalIgnoreCase)) >= 0)
                {
                    int start = i + 4, end = start;
                    while (end < s.Length && char.IsLetterOrDigit(s[end])) end++;
                    if (end > start) codes.Add(s.Substring(start, end - start));
                    i = end;
                }
            }
            return codes;
        }

        /// <summary>Intrinsically-volatile fault CLASSES — faults that hide when you probe them and so
        /// cannot be refuted on one clean pass. This is only the class check on the key; a structural
        /// fault's per-scan intermittent grammar arrives separately via <see cref="RankedFault.Volatile"/>
        /// (SpawnHypotheses ORs the two), NOT a process-global key lookup — that would leak one car's
        /// intermittent verdict onto a later car's plain code.</summary>
        private static bool IsVolatileFault(string faultKey)
        {
            if (string.IsNullOrEmpty(faultKey)) return false;
            string k = faultKey.ToUpperInvariant();
            return k.Contains("BUSFAULT") || k.Contains("INTERMITTENT") || k.Contains("SENSORDROPOUT")
                   || k.Contains("LOSTCOMM");
        }
    }
