// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Tester Present Specialist Automotive Solutions — Generic Platform Calibration
//
//  The always-available fallback calibration.  Values are broad, spec-generic
//  defaults for a typical 4-cylinder gasoline engine, seeded from SAE J1979
//  norms and the fuel-trim thresholds already documented in the TES workshop
//  knowledge base (±5 % normal / ±10 % suspicious / ±25 % code-setting).
//
//  EVERY value here is unvalidated by construction — IsValidated is always false
//  — so any module resolving to the generic calibration reports advisory-only.
//  That is the correct posture: without a platform-specific characterisation we
//  are guessing, and the layer says so out loud.
// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
using System;

namespace TesterPresent.OBD2.Intelligence
{
    [RequiresValidation("Generic spec-seeded defaults — never validated against a specific platform.")]
    public sealed class GenericCalibration : PlatformCalibration
    {
        public override string PlatformId => "Generic";
        public override string DisplayName => "Generic (spec defaults, advisory only)";

        // Generic is advisory by definition, regardless of individual flags.
        public override bool IsValidated => false;

        public GenericCalibration()
        {
            // ── Engine geometry (typical 2.0L I4) ──
            Seed("Engine.Cylinders", 4, "generic I4 assumption");
            Seed("Engine.DisplacementCc", 2000, "generic 2.0L assumption");
            Seed("Engine.CompressionRatio", 10.0, "generic gasoline NA");
            Seed("Engine.IdleRpm", 750, "generic warm idle");
            Seed("Engine.VolumetricEff", 0.85, "generic peak VE");

            // ── M1 fuel-trim surface thresholds (workshop norms) ──
            Seed("M1.NormalTrimPct", 5.0, "SAE/workshop: within ±5% is healthy");
            Seed("M1.SuspiciousTrimPct", 10.0, "workshop: ±10% warrants investigation");
            Seed("M1.CodeSettingTrimPct", 25.0, "workshop: ±25% typically sets P0171/P0172");
            Seed("M1.BankAsymmetryPct", 8.0, "bank-to-bank delta suggesting single-bank fault");
            Seed("M1.MinCellSamples", 5, "min samples per RPM×Load cell to trust it");

            // ── M2 crank angular-velocity thresholds ──
            Seed("M2.CrankCoVFailPct", 18.0, "RelativeCompression: >18% CoV = uneven compression");
            Seed("M2.IdleCoVWarnPct", 5.0, "idle RPM ripple CoV warning band");
            Seed("M2.MinCrankRpm", 100, "lower bound of a valid cranking window");
            Seed("M2.MaxCrankRpm", 800, "upper bound of a valid cranking window");

            // ── T2 analytical-redundancy tolerances ──
            Seed("T2.MapModelTolKpa", 12.0, "speed-density MAP prediction tolerance");
            Seed("T2.IatEctColdDeltaC", 8.0, "cold-soak IAT≈ECT expected agreement");

            // ── T5 electrical transient thresholds ──
            Seed("T5.CrankVoltageMinV", 9.6, "healthy battery holds ≥9.6V under crank");
            Seed("T5.RunVoltageMinV", 13.2, "charging system floor while running");
            Seed("T5.RunVoltageMaxV", 15.0, "overcharge ceiling");

            // ── T3 prognostic drift ──
            Seed("T3.VeDriftAlarmPct", 8.0, "VE drop from baseline flagged as degradation");
        }
    }
}
