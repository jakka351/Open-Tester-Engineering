//  Platform-specific constants for the Ford FG/FG-X Falcon and the Barra 4.0L
//  inline-six family (BF/FG, NA and turbo).  Geometry is from published Ford
//  engine specifications; diagnostic thresholds are seeded from the Barra's
//  known idle/firing behaviour and the CGDS-era workshop data already in TES.
//
//  ⚠ EVERY value is marked [RequiresValidation] / seeded (unvalidated).  Per the
//  brief and CLAUDE.md ("emulator passing is a smoke test, not a passing grade"),
