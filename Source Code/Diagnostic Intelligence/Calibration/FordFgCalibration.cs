using System;

namespace TesterPresent.OBD2.Intelligence
{
    [RequiresValidation("Barra I6 geometry from published Ford specs; thresholds spec-seeded, not vehicle-validated.")]
    public sealed class FordFgCalibration : PlatformCalibration
    {
        public override string PlatformId => "FordFG";
        public override string DisplayName => "Ford FG Falcon — Barra 4.0L I6 (advisory)";

        /// <summary>True for the Ford OEM bucket on a Broadmeadows Falcon VIN (6FP…/6MP… WMI)
        /// or when the platform key is explicitly FordFG.</summary>
        public static bool Matches(OEMManufacturer oem, string vin)
        {
            if (oem != OEMManufacturer.Ford) return false;
            if (string.IsNullOrEmpty(vin)) return false;
            string wmi = vin.Length >= 3 ? vin.Substring(0, 3).ToUpperInvariant() : "";
            // Ford Australia Broadmeadows Falcon/Territory WMIs.
            return wmi == "6FP" || wmi == "6MP" || wmi == "MPB";
        }

        public FordFgCalibration()
        {
            // ── Barra 4.0L I6 geometry (published Ford specifications) ──
            Seed("Engine.Cylinders", 6, "Barra I6");
            Seed("Engine.DisplacementCc", 3984, "Ford spec: 3984 cc");
            Seed("Engine.BoreMm", 92.26, "Ford spec: 92.26 mm");
            Seed("Engine.StrokeMm", 99.31, "Ford spec: 99.31 mm");
            Seed("Engine.CompressionRatio", 10.3, "Ford spec: 10.3:1 (NA); turbo ~8.7:1");
            Seed("Engine.IdleRpm", 700, "Barra warm idle ≈650–750 rpm");
            Seed("Engine.VolumetricEff", 0.88, "Barra peak VE estimate");
            // Firing order 1-5-3-6-2-4 encoded as a scalar hint for M2 cylinder mapping.
            Seed("Engine.FiringOrderHint", 153624, "Barra firing order 1-5-3-6-2-4");

            // ── M1 fuel-trim surface (CGDS-era workshop bands) ──
            Seed("M1.NormalTrimPct", 5.0, "Barra healthy trim band");
            Seed("M1.SuspiciousTrimPct", 10.0, "Barra investigation threshold");
            Seed("M1.CodeSettingTrimPct", 22.0, "Barra tends to set adaptive codes near ±22%");
            Seed("M1.BankAsymmetryPct", 8.0, "single I6 head — asymmetry points to injector/localised leak");
            Seed("M1.MinCellSamples", 5, "min samples per RPM×Load cell");

            // ── M2 crank angular-velocity (6-cyl, firing every 120° crank) ──
            Seed("M2.CrankCoVFailPct", 16.0, "I6 smoother than I4 — tighter CoV gate");
            Seed("M2.IdleCoVWarnPct", 4.0, "Barra idle is smooth; small ripple is significant");
            Seed("M2.MinCrankRpm", 120, "Barra crank window lower bound");
            Seed("M2.MaxCrankRpm", 750, "Barra crank window upper bound");

            // ── T2 analytical-redundancy ──
            Seed("T2.MapModelTolKpa", 10.0, "speed-density tolerance for Barra");
            Seed("T2.IatEctColdDeltaC", 6.0, "cold-soak IAT≈ECT for Barra sensor placement");

            // ── T5 electrical (Barra + FG charging system) ──
            Seed("T5.CrankVoltageMinV", 9.8, "FG cranking voltage floor");
            Seed("T5.RunVoltageMinV", 13.4, "FG smart-charge floor");
            Seed("T5.RunVoltageMaxV", 15.0, "FG smart-charge ceiling");

            // ── T3 prognostic drift ──
            Seed("T3.VeDriftAlarmPct", 8.0, "Barra VE drop flag (valve carbon / cam timing)");
        }
    }
}
