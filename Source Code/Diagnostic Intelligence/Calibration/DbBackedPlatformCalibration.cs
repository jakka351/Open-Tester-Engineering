// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Tester Present Specialist Automotive Solutions — DB-backed Platform Calibration
//
//  Layers field-validated calibration overrides (from CalibrationStore) on top of a
//  base platform calibration (FordFg / Generic — spec-seeded).  For any key the store
//  has validated, the module reads a REAL value with validated=true and may drop its
//  advisory posture; keys not in the store keep the base's spec-seeded (advisory)
//  value.  A platform is fully promoted out of advisory only once every constant its
//  modules read is validated in the store — the honest bar the owner asked for.
// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
using System.Collections.Generic;

namespace TesterPresent.OBD2.Intelligence
{
    /// <summary>A base platform calibration overlaid with field-validated overrides.</summary>
    public sealed class DbBackedPlatformCalibration : PlatformCalibration
    {
        private readonly string _platformId;
        private readonly string _displayName;

        public override string PlatformId => _platformId;
        public override string DisplayName => _displayName;

        public DbBackedPlatformCalibration(PlatformCalibration baseCal,
                                           IReadOnlyDictionary<string, CalibrationValue> overrides)
        {
            _platformId = baseCal?.PlatformId ?? "None";

            // Start from the base's spec-seeded set.
            if (baseCal != null)
                foreach (var kv in baseCal.All) Values[kv.Key] = kv.Value;

            // Overlay the field values; a validated override lets the consuming module
            // report confirmed instead of advisory for that key.
            bool anyValidated = false;
            if (overrides != null)
                foreach (var kv in overrides)
                {
                    Values[kv.Key] = kv.Value;
                    if (kv.Value != null && kv.Value.Validated) anyValidated = true;
                }

            string baseName = baseCal?.DisplayName ?? "No calibration";
            _displayName = anyValidated ? baseName + " (field-validated)" : baseName;
        }
    }
}
