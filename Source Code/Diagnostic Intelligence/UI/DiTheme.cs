// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Tester Present Specialist Automotive Solutions — Diagnostic Intelligence dark theme
//
//  The rest of the Advanced Diagnostics dialogs use AdvDiagTheme, a LIGHT
//  engineering-tool skin.  The Diagnostic Intelligence workbench instead matches
//  the main TES shell — the dark "carbon" palette in UI/TesTheme.cs (near-black
//  navy surfaces, spring-green accent).  DiTheme mirrors AdvDiagTheme's member
//  surface (same names: BG_*, FG_*, ACCENT_*, fonts, MakeRoot/MakeBanner) but with
//  dark values pulled from TesTheme, so the DI controls can reference DiTheme.X
//  wherever they used AdvDiagTheme.X and simply come out dark.
//
//  Crucially, ApplyChrome does NOT run AdvDiagTheme's ApplyDeep light re-color
//  pass — that pass is exactly what was forcing the workbench light.  It applies
//  a dark title bar and a dark child-styling pass instead.
// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
using System;
using System.Drawing;
using System.Drawing.Drawing2D;
using System.Runtime.InteropServices;
using System.Windows.Forms;
using TesterPresent.OBD2.UI;

namespace TesterPresent.OBD2.Intelligence.UI
{
    /// <summary>Dark carbon theme for the Diagnostic Intelligence dialogs, matching the TES shell.</summary>
    internal static class DiTheme
    {
        // ── Palette (mapped onto the shared TesTheme carbon tokens) ─────────
        public static readonly Color BG_DARK   = TesTheme.BgApp;     // window / page backdrop
        public static readonly Color BG_PANEL  = TesTheme.BgCard;    // panel base
        public static readonly Color BG_PANEL2 = TesTheme.BgChip;    // card / raised surface
        public static readonly Color BG_INPUT  = TesTheme.BgInset;   // input well
        public static readonly Color BG_DETAIL = TesTheme.BgInset;   // detail / console well
        public static readonly Color BG_HEADER = TesTheme.BgBar;     // banner
        public static readonly Color BG_HOVER  = TesTheme.BgHover;   // hover wash

        public static readonly Color FG_PRIMARY = TesTheme.TextHi;   // headings / values
        public static readonly Color FG_SECOND  = TesTheme.Text;     // body
        public static readonly Color FG_DIM     = TesTheme.TextDim;  // captions / hint

        public static readonly Color ACCENT_BLUE = TesTheme.Info;    // info / low severity
        public static readonly Color ACCENT_TEAL = TesTheme.Accent;  // primary spring-green CTA
        public static readonly Color ACCENT_AMB  = TesTheme.Warn;    // warning / advisory
        public static readonly Color ACCENT_RED  = TesTheme.Bad;     // error / critical
        public static readonly Color ACCENT_GRN  = TesTheme.Good;    // success / pass
        public static readonly Color ACCENT_GOLD = TesTheme.Accent;  // accent rule (green in TES)
        public static readonly Color ACCENT_VIO  = Color.FromArgb(0x9A, 0x6C, 0xF2);

        public static readonly Color GRID_LINE = TesTheme.BorderSoft; // faint divider
        public static readonly Color BORDER     = TesTheme.Border;    // panel / input border

        // ── Fonts (reuse the shared AdvDiagTheme instances — same faces, dark-safe) ──
        public static readonly Font UiFont      = AdvDiagTheme.UiFont;
        public static readonly Font UiBold      = AdvDiagTheme.UiBold;
        public static readonly Font UiSmall     = AdvDiagTheme.UiSmall;
        public static readonly Font UiSmallBold = AdvDiagTheme.UiSmallBold;
        public static readonly Font Mono        = AdvDiagTheme.Mono;
        public static readonly Font MonoBold    = AdvDiagTheme.MonoBold;
        public static readonly Font MonoSmall   = AdvDiagTheme.MonoSmall;
        public static readonly Font Title       = AdvDiagTheme.Title;
        public static readonly Font Subtitle    = AdvDiagTheme.Subtitle;
        public static readonly Font Tag         = AdvDiagTheme.Tag;

        // ── Root layout (banner row + fill row), dark ───────────────────────
        public static TableLayoutPanel MakeRoot(int bannerHeight = 76)
        {
            var t = new TableLayoutPanel
            {
                Dock = DockStyle.Fill, ColumnCount = 1, RowCount = 2,
                BackColor = BG_DARK, Margin = new Padding(0), Padding = new Padding(0),
            };
            t.RowStyles.Add(new RowStyle(SizeType.Absolute, bannerHeight));
            t.RowStyles.Add(new RowStyle(SizeType.Percent, 100f));
            t.ColumnStyles.Add(new ColumnStyle(SizeType.Percent, 100f));
            return t;
        }

        /// <summary>Dark banner: navy bar, brand hex mark, title + subtitle, a green
        /// accent rule along the bottom, and a right-aligned counter label.</summary>
        public static Panel MakeBanner(string title, string subtitle, out Label counterLabel)
        {
            var counter = new Label
            {
                AutoSize = true, ForeColor = FG_DIM, Font = MonoSmall,
                BackColor = Color.Transparent, Text = "",
            };
            counterLabel = counter;

            var bar = new Panel { Dock = DockStyle.Fill, BackColor = BG_HEADER };
            bar.Paint += (s, e) =>
            {
                var g = e.Graphics;
                g.SmoothingMode = SmoothingMode.AntiAlias;
                var rc = bar.ClientRectangle;
                using (var bg = new SolidBrush(BG_HEADER)) g.FillRectangle(bg, rc);

                // Brand hex mark on the left.
                int cx = 30, cy = rc.Height / 2, r = 15;
                using (var pen = new Pen(ACCENT_TEAL, 2f))
                    g.DrawPolygon(pen, Hexagon(cx, cy, r));
                using (var pen2 = new Pen(Color.FromArgb(90, ACCENT_TEAL), 1f))
                    g.DrawPolygon(pen2, Hexagon(cx, cy, r - 5));

                // Title + subtitle.
                using (var tb = new SolidBrush(FG_PRIMARY))
                    g.DrawString(title ?? "", Title, tb, 58, cy - 20);
                using (var sb = new SolidBrush(TesTheme.TextMut))
                    g.DrawString(subtitle ?? "", Subtitle, sb, 60, cy + 6);

                // Green accent rule along the bottom edge.
                using (var pen = new Pen(ACCENT_TEAL, 2f))
                    g.DrawLine(pen, rc.X, rc.Bottom - 1, rc.Right, rc.Bottom - 1);
            };

            counter.Location = new Point(0, 8);
            counter.Anchor = AnchorStyles.Top | AnchorStyles.Right;
            bar.Controls.Add(counter);
            bar.Resize += (s, e) => counter.Location = new Point(bar.Width - counter.Width - 16, 12);
            return bar;
        }

        private static PointF[] Hexagon(float cx, float cy, float r)
        {
            var pts = new PointF[6];
            for (int i = 0; i < 6; i++)
            {
                double a = Math.PI / 180.0 * (60 * i - 30);
                pts[i] = new PointF(cx + (float)(r * Math.Cos(a)), cy + (float)(r * Math.Sin(a)));
            }
            return pts;
        }

        // ── Chrome ──────────────────────────────────────────────────────────
        public static void ApplyChrome(Form f)
        {
            if (f == null) return;
            f.BackColor = BG_DARK;
            f.ForeColor = FG_PRIMARY;
            f.Font = UiFont;
            try { f.AutoScaleMode = AutoScaleMode.Dpi; } catch { }
            try { f.StartPosition = FormStartPosition.CenterParent; } catch { }
            try { var ico = FormIconHelper.SharedIcon; if (ico != null) f.Icon = ico; f.ShowIcon = true; } catch { }

            f.HandleCreated += (s, e) => TrySetDarkTitleBar(f);
            // Dark-recolour any child that still holds a WinForms default colour,
            // AFTER the dialog has built its tree (Load fires post-construction).
            EventHandler onLoad = null;
            onLoad = (s, e) => { try { StyleTree(f); } catch { } f.Load -= onLoad; };
            f.Load += onLoad;
        }

        [DllImport("dwmapi.dll")]
        private static extern int DwmSetWindowAttribute(IntPtr hwnd, int attr, ref int value, int size);

        private static void TrySetDarkTitleBar(Form f)
        {
            try
            {
                int on = 1;
                // DWMWA_USE_IMMERSIVE_DARK_MODE = 20 (Win10 2004+); 19 on older builds.
                if (DwmSetWindowAttribute(f.Handle, 20, ref on, sizeof(int)) != 0)
                    DwmSetWindowAttribute(f.Handle, 19, ref on, sizeof(int));
            }
            catch { }
        }

        /// <summary>Recolour a control tree to the dark palette — only touching
        /// properties that still hold WinForms defaults, so explicit dark colours
        /// the dialog set are preserved.</summary>
        public static void StyleTree(Control root)
        {
            if (root == null) return;
            StyleOne(root);
            foreach (Control c in root.Controls) StyleTree(c);
        }

        private static void StyleOne(Control c)
        {
            switch (c)
            {
                case Form _:
                    return;
                case Label lbl:
                    if (lbl.ForeColor == SystemColors.ControlText) lbl.ForeColor = FG_PRIMARY;
                    if (lbl.BackColor == SystemColors.Control) lbl.BackColor = Color.Transparent;
                    return;
                case TextBox tb:
                    if (tb.BackColor == SystemColors.Window) tb.BackColor = BG_INPUT;
                    if (tb.ForeColor == SystemColors.WindowText) tb.ForeColor = FG_PRIMARY;
                    if (tb.BorderStyle == BorderStyle.Fixed3D) tb.BorderStyle = BorderStyle.FixedSingle;
                    return;
                case RichTextBox rtb:
                    if (rtb.BackColor == SystemColors.Window) rtb.BackColor = BG_DETAIL;
                    if (rtb.ForeColor == SystemColors.WindowText) rtb.ForeColor = FG_PRIMARY;
                    return;
                case NumericUpDown nud:
                    nud.BackColor = BG_INPUT;
                    nud.ForeColor = FG_PRIMARY;
                    if (nud.BorderStyle == BorderStyle.Fixed3D) nud.BorderStyle = BorderStyle.FixedSingle;
                    return;
                case ComboBox cb:
                    if (cb.FlatStyle == FlatStyle.Standard) cb.FlatStyle = FlatStyle.Flat;
                    if (cb.BackColor == SystemColors.Window) cb.BackColor = BG_INPUT;
                    if (cb.ForeColor == SystemColors.WindowText) cb.ForeColor = FG_PRIMARY;
                    return;
                case ListBox lst:
                    if (lst.BackColor == SystemColors.Window) lst.BackColor = BG_INPUT;
                    if (lst.ForeColor == SystemColors.WindowText) lst.ForeColor = FG_PRIMARY;
                    return;
                case CheckBox chk:
                    if (chk.ForeColor == SystemColors.ControlText) chk.ForeColor = FG_SECOND;
                    if (chk.BackColor == SystemColors.Control) chk.BackColor = Color.Transparent;
                    return;
                case Button btn:
                    // Leave buttons that already carry an explicit accent (Flat + non-default back).
                    if (btn.FlatStyle == FlatStyle.Standard && btn.BackColor == SystemColors.Control)
                    {
                        btn.FlatStyle = FlatStyle.Flat;
                        btn.BackColor = BG_PANEL2;
                        btn.ForeColor = FG_PRIMARY;
                        btn.FlatAppearance.BorderColor = BORDER;
                    }
                    return;
                case Panel _: // also covers TableLayoutPanel / FlowLayoutPanel (subclasses)
                    if (c.BackColor == SystemColors.Control) c.BackColor = BG_PANEL;
                    return;
                default:
                    return;
            }
        }
    }
}
