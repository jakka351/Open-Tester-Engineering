// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Tester Present Specialist Automotive Solutions — Diagnostic Module Catalog
//
//  The single place that knows every built-in Tier-1 and Tier-2 module and the
//  order they run in.  Order matters: the two COMPOSING modules (M6 Bayesian,
//  M7 confirmation) read the hypotheses earlier modules produced this pass
//  (DiagnosticContext.PriorResults), so they are registered LAST.
//
//  CreateAll() returns fresh instances so an engine (and the self-test) each get
//  their own module set.
// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
using System.Collections.Generic;
using TesterPresent.OBD2.Intelligence.Tier1;
using TesterPresent.OBD2.Intelligence.Tier2;

namespace TesterPresent.OBD2.Intelligence
{
    /// <summary>Factory for the built-in diagnostic-intelligence modules.</summary>
    public static class ModuleCatalog
    {
        /// <summary>All built-in modules, in run order.  Composing modules (M6, M7)
        /// come last so their inputs (earlier hypotheses) are already populated.</summary>
        public static IReadOnlyList<IDiagnosticModule> CreateAll()
        {
            return new List<IDiagnosticModule>
            {
                // ── Tier 1 signal-inversion (evidence producers) ──
                new FuelTrimSurfaceModule(),          // M1
                new CrankAngularVelocityModule(),     // M2
                new BusFaultLocalizationModule(),     // M3
                new FleetBaselineModule(),            // M4
                new IntermittentCaptureModule(),      // M5

                // ── Tier 2 model-based / prognostic (evidence producers) ──
                new AnalyticalRedundancyModule(),     // T2
                new ObserverResidualModule(),         // T1
                new ParameterEstimationModule(),      // T3
                new ElectricalTransientModule(),      // T5
                new FrequencyResponseModule(),        // T4
                new VibrationMonitorModule(),         // T6
                new FleetAnomalyModule(),             // T7
                new CylinderPressureModule(),         // T8

                // ── Composing modules — MUST be last (read PriorResults) ──
                new BayesianHypothesisModule(),       // M6
                new BidirectionalConfirmModule(),     // M7
            };
        }

        /// <summary>Only the Tier-1 modules (M1–M7), for a Tier-1-only engine.</summary>
        public static IReadOnlyList<IDiagnosticModule> CreateTier1()
        {
            return new List<IDiagnosticModule>
            {
                new FuelTrimSurfaceModule(),          // M1
                new CrankAngularVelocityModule(),     // M2
                new BusFaultLocalizationModule(),     // M3
                new FleetBaselineModule(),            // M4
                new IntermittentCaptureModule(),      // M5
                new BayesianHypothesisModule(),       // M6
                new BidirectionalConfirmModule(),     // M7
            };
        }
    }
}
