// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Tester Present Specialist Automotive Solutions — Type-K thermocouple + NTC math (NIST ITS-90)
//
//  The WBo2 frame carries each thermocouple as a raw 10-bit ADC count (gain ×1, no ×8 scaling).
//  Converting that to an absolute temperature needs three pieces:
//    1. ADC count → thermocouple EMF (mV) — a board-specific scale the operator calibrates
//       (the controller doc defers the exact channel gain to a separate page), exposed as
//       WidebandSerial.TcMillivoltsPerCount.
//    2. Cold-junction compensation (CJC): the EMF a Type-K junction at the terminal-block
//       temperature would produce, added to the measured EMF before conversion.  The board's
//       thermistor reads that terminal temperature (or a fixed ambient is assumed).
//    3. EMF (mV) → °C via the standard NIST ITS-90 Type-K inverse polynomials.
//
//  The polynomials here are the published NIST ITS-90 Type-K coefficients (exact, not curve-fit
//  guesses) — verified against the reference points 0 °C↔0 mV, 100 °C↔4.096 mV, 1000 °C↔41.276 mV.
// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
using System;

namespace TesterPresent.OBD2.Wideband
{
    public static class Thermocouple
    {
        // ── Type-K forward: temperature (°C) → EMF (mV), reference junction at 0 °C ──────────
        // Used for cold-junction compensation.  Two ranges; the 0..1372 °C range includes the
        // characteristic exponential term.
        public static double KTypeMv(double tC)
        {
            if (tC < 0)
            {
                double[] c = { 0.0, 0.394501280250e-1, 0.236223735980e-4, -0.328589067840e-6,
                               -0.499048287770e-8, -0.675090591730e-10, -0.574103274280e-12,
                               -0.310888728940e-14, -0.104516093650e-16, -0.198892668780e-19,
                               -0.163226974860e-22 };
                return Poly(c, tC);
            }
            else
            {
                double[] c = { -0.176004136860e-1, 0.389212049750e-1, 0.185587700320e-4,
                               -0.994575928740e-7, 0.318409457190e-9, -0.560728448890e-12,
                                0.560750590590e-15, -0.320207200030e-18, 0.971511471520e-22,
                               -0.121047212750e-25 };
                double a0 = 0.118597600000e0, a1 = -0.118343200000e-3, a2 = 0.126968600000e3;
                return Poly(c, tC) + a0 * Math.Exp(a1 * (tC - a2) * (tC - a2));
            }
        }

        // ── Type-K inverse: EMF (mV) → temperature (°C) ─────────────────────────────────────
        public static double KTypeC(double mv)
        {
            if (mv < -5.891) return -200;
            if (mv > 54.886) return 1372;
            double[] d;
            if (mv < 0)
                d = new[] { 0.0, 2.5173462e1, -1.1662878e0, -1.0833638e0, -8.9773540e-1,
                            -3.7342377e-1, -8.6632643e-2, -1.0450598e-2, -5.1920577e-4, 0.0 };
            else if (mv < 20.644)
                d = new[] { 0.0, 2.508355e1, 7.860106e-2, -2.503131e-1, 8.315270e-2,
                            -1.228034e-2, 9.804036e-4, -4.413030e-5, 1.057734e-6, -1.052755e-8 };
            else
                d = new[] { -1.318058e2, 4.830222e1, -1.646031e0, 5.464731e-2, -9.650715e-4,
                             8.802193e-6, -3.110810e-8, 0.0, 0.0, 0.0 };
            return Poly(d, mv);
        }

        /// <summary>
        /// Full Type-K reading: raw thermocouple ADC count + cold-junction temperature → °C.
        /// mvPerCount is the board-specific ADC→EMF scale.
        /// </summary>
        public static double ReadTypeK(int adcCount, double mvPerCount, double coldJunctionC)
        {
            if (adcCount <= 0) return double.NaN;
            double emfMeasured = adcCount * mvPerCount;          // junction EMF relative to the cold junction
            double emfTotal = emfMeasured + KTypeMv(coldJunctionC); // shift to a 0 °C reference
            return KTypeC(emfTotal);
        }

        /// <summary>
        /// NTC thermistor ADC count → °C via the Beta model, assuming a low-side thermistor in a
        /// simple divider (pull-up seriesR to Vref, thermistor to ground): Vadc = Vref·Rt/(Rt+Rs).
        /// </summary>
        public static double NtcTempC(int adcCount, int adcMax, double seriesR, double r25, double beta)
        {
            if (adcCount <= 0 || adcCount >= adcMax) return double.NaN;
            double ratio = adcCount / (double)adcMax;            // = Rt/(Rt+Rs)
            if (ratio <= 0 || ratio >= 1) return double.NaN;
            double rt = seriesR * ratio / (1.0 - ratio);
            double tK = 1.0 / (1.0 / 298.15 + Math.Log(rt / r25) / beta);
            return tK - 273.15;
        }

        private static double Poly(double[] coef, double x)
        {
            double sum = 0, p = 1;
            for (int i = 0; i < coef.Length; i++) { sum += coef[i] * p; p *= x; }
            return sum;
        }
    }
}
