// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Tester Present Specialist Automotive Solutions — Bluetooth radio state / enable (in-process WinRT)
//  BtRadio.cs
//
//  Replaces the PowerShell shell-out in VehicleBluetoothTestingDialog.EnableBluetoothRadio()
//  with a direct Windows.Devices.Radios call. Same capability boundary: the host radio is a
//  dual-mode (Classic + LE) peer/scanner. This just reports its on/off state and turns it on.
// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
using System;
using System.Linq;
using System.Threading.Tasks;
using Windows.Devices.Radios;

namespace TesterPresent.OBD2.Bluetooth
{
    public static class BtRadio
    {
        /// <summary>True if a Bluetooth radio exists and is On.</summary>
        public static async Task<bool> IsOnAsync()
        {
            try
            {
                var bt = await GetBluetoothRadioAsync().ConfigureAwait(false);
                return bt != null && bt.State == RadioState.On;
            }
            catch { return false; }
        }

        /// <summary>Human-readable radio state: "On" / "Off" / "Disabled" / "No Bluetooth radio".</summary>
        public static async Task<string> StateTextAsync()
        {
            try
            {
                var bt = await GetBluetoothRadioAsync().ConfigureAwait(false);
                if (bt == null) return "No Bluetooth radio";
                return bt.State.ToString();
            }
            catch (Exception ex) { return "Unknown (" + ex.Message + ")"; }
        }

        /// <summary>Attempt to switch the Bluetooth radio On. Returns true on success.</summary>
        public static async Task<bool> TryEnableAsync()
        {
            try
            {
                var access = await WinRt.Await(Radio.RequestAccessAsync(), 6000).ConfigureAwait(false);
                if (access != RadioAccessStatus.Allowed) return false;
                var bt = await GetBluetoothRadioAsync().ConfigureAwait(false);
                if (bt == null) return false;
                if (bt.State == RadioState.On) return true;
                var result = await WinRt.Await(bt.SetStateAsync(RadioState.On), 6000).ConfigureAwait(false);
                return result == RadioAccessStatus.Allowed;
            }
            catch { return false; }
        }

        private static async Task<Radio> GetBluetoothRadioAsync()
        {
            var radios = await WinRt.Await(Radio.GetRadiosAsync(), 6000).ConfigureAwait(false);
            return radios?.FirstOrDefault(r => r.Kind == RadioKind.Bluetooth);
        }
    }
}
