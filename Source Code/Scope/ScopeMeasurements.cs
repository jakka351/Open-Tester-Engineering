// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Tester Present Specialist Automotive Solutions — USB Oscilloscope HAL: automated measurements
//  Copyright (c) 2026 Benjamin Jack Leighton. All rights reserved.
//
//  Standard per-channel scalar measurements over one capture. Frequency/duty use mid-level
//  crossings with hysteresis (5% of Vpp) so ADC noise on a slow edge doesn't double-count.
// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
using System;

namespace TesterPresent.OBD2.Scope
{
    public sealed class ChannelMeasurements
    {
        public double Min, Max, PeakToPeak, Mean, Rms;
        public double FrequencyHz;   // NaN when no full period found
        public double DutyCycle;     // 0..1, NaN when no full period found

        public static ChannelMeasurements Compute(float[] samples, int count, double sampleIntervalSeconds)
        {
            var m = new ChannelMeasurements { FrequencyHz = double.NaN, DutyCycle = double.NaN };
            if (samples == null || count < 2) return m;
            if (count > samples.Length) count = samples.Length;

            double sum = 0, sumSq = 0;
            float mn = samples[0], mx = samples[0];
            for (int i = 0; i < count; i++)
            {
                float v = samples[i];
                if (v < mn) mn = v;
                if (v > mx) mx = v;
                sum += v;
                sumSq += (double)v * v;
            }
            m.Min = mn;
            m.Max = mx;
            m.PeakToPeak = mx - mn;
            m.Mean = sum / count;
            m.Rms = Math.Sqrt(sumSq / count);

            // Mid-level crossing analysis with hysteresis.
            double mid = (mn + mx) / 2.0;
            double hyst = m.PeakToPeak * 0.05;
            if (m.PeakToPeak <= 1e-9 || sampleIntervalSeconds <= 0) return m;

            int firstRise = -1, lastRise = -1, riseCount = 0;
            bool state = samples[0] > mid;      // true = high
            for (int i = 1; i < count; i++)
            {
                float v = samples[i];
                if (!state && v > mid + hyst)
                {
                    state = true;
                    if (firstRise < 0) firstRise = i;
                    lastRise = i;
                    riseCount++;
                }
                else if (state && v < mid - hyst)
                {
                    state = false;
                }
            }

            if (riseCount >= 2 && lastRise > firstRise)
            {
                double periods = riseCount - 1;
                double periodSeconds = (lastRise - firstRise) * sampleIntervalSeconds / periods;
                if (periodSeconds > 0)
                {
                    m.FrequencyHz = 1.0 / periodSeconds;
                    // Duty over WHOLE periods only ([firstRise, lastRise)) — partial periods at
                    // the window edges bias the ratio by up to ±(1/(2·periods)) otherwise, which
                    // makes a stable square wave's duty jitter every roll refresh.
                    long high = 0;
                    bool st = true;   // just rose at firstRise
                    for (int i = firstRise; i < lastRise; i++)
                    {
                        float v = samples[i];
                        if (st && v < mid - hyst) st = false;
                        else if (!st && v > mid + hyst) st = true;
                        if (st) high++;
                    }
                    m.DutyCycle = high / (double)(lastRise - firstRise);
                }
            }
            return m;
        }
    }
}
