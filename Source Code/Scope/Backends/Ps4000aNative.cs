using System;
using System.Runtime.InteropServices;
using System.Text;

namespace TesterPresent.OBD2.Scope
{
    internal static class Ps4000aNative
    {
        private const string DRIVER = "ps4000a.dll";

        // PICO_STATUS values this backend branches on (PicoStatus.h).
        internal const uint PICO_OK = 0x00000000;
        internal const uint PICO_POWER_SUPPLY_CONNECTED = 0x00000119;
        internal const uint PICO_POWER_SUPPLY_NOT_CONNECTED = 0x0000011A;
        internal const uint PICO_USB3_0_DEVICE_NON_USB3_0_PORT = 0x0000011E;

        internal enum Channel : int
        {
            A, B, C, D,
            Max4Channels,
            E = Max4Channels, F, G, H,
            External,
        }

        internal enum Coupling : int { AC, DC }

        // PicoConnectProbeRange — plain ±ranges, PICO_X1_PROBE_10MV=0 .. PICO_X1_PROBE_200V=13.
        internal static readonly double[] RangeVolts =
            { 0.01, 0.02, 0.05, 0.1, 0.2, 0.5, 1, 2, 5, 10, 20, 50, 100, 200 };

        internal enum ThresholdDirection : int { Above, Below, Rising, Falling, RisingOrFalling }

        internal enum DownSamplingMode : int { None = 0, Aggregate = 1, Decimate = 2, Average = 4 }

        internal enum ReportedTimeUnits : int { FemtoSeconds, PicoSeconds, NanoSeconds, MicroSeconds, MilliSeconds, Seconds }

        internal enum InfoType : short
        {
            DriverVersion, UsbVersion, HardwareVersion, VariantInfo, BatchAndSerial,
            CalDate, KernelVersion, DigitalHardwareVersion, AnalogueHardwareVersion,
        }

        internal delegate void ps4000aBlockReady(short handle, short status, IntPtr pVoid);

        internal delegate void ps4000aStreamingReady(
            short handle, int noOfSamples, uint startIndex, short overflow,
            uint triggerAt, short triggered, short autoStop, IntPtr pVoid);

        [DllImport(DRIVER, EntryPoint = "ps4000aEnumerateUnits")]
        internal static extern uint EnumerateUnits(out short count, StringBuilder serials, ref short serialLength);

        [DllImport(DRIVER, EntryPoint = "ps4000aOpenUnit")]
        internal static extern uint OpenUnit(out short handle, StringBuilder serial);

        [DllImport(DRIVER, EntryPoint = "ps4000aChangePowerSource")]
        internal static extern uint ChangePowerSource(short handle, uint status);

        [DllImport(DRIVER, EntryPoint = "ps4000aCloseUnit")]
        internal static extern uint CloseUnit(short handle);

        [DllImport(DRIVER, EntryPoint = "ps4000aGetUnitInfo")]
        internal static extern uint GetUnitInfo(short handle, StringBuilder infoString, short stringLength, out short requiredSize, InfoType info);

        [DllImport(DRIVER, EntryPoint = "ps4000aMaximumValue")]
        internal static extern uint MaximumValue(short handle, out short value);

        [DllImport(DRIVER, EntryPoint = "ps4000aSetChannel")]
        internal static extern uint SetChannel(short handle, Channel channel, short enabled, Coupling dc, int range, float analogOffset);

        [DllImport(DRIVER, EntryPoint = "ps4000aSetSimpleTrigger")]
        internal static extern uint SetSimpleTrigger(short handle, short enable, Channel channel, short threshold, ThresholdDirection direction, uint delay, short autotriggerMs);

        [DllImport(DRIVER, EntryPoint = "ps4000aGetTimebase")]
        internal static extern uint GetTimebase(short handle, uint timebase, int noSamples, out int timeIntervalNanoseconds, out int maxSamples, uint segmentIndex);

        [DllImport(DRIVER, EntryPoint = "ps4000aRunBlock")]
        internal static extern uint RunBlock(short handle, int noOfPreTriggerSamples, int noOfPostTriggerSamples, uint timebase, out int timeIndisposedMs, uint segmentIndex, ps4000aBlockReady lpReady, IntPtr pVoid);

        [DllImport(DRIVER, EntryPoint = "ps4000aSetDataBuffer")]
        internal static extern uint SetDataBuffer(short handle, Channel channel, short[] buffer, int bufferLth, uint segmentIndex, DownSamplingMode ratioMode);

        [DllImport(DRIVER, EntryPoint = "ps4000aGetValues")]
        internal static extern uint GetValues(short handle, uint startIndex, ref uint noOfSamples, uint downSampleRatio, DownSamplingMode downSampleRatioMode, uint segmentIndex, out short overflow);

        [DllImport(DRIVER, EntryPoint = "ps4000aStop")]
        internal static extern uint Stop(short handle);

        [DllImport(DRIVER, EntryPoint = "ps4000aRunStreaming")]
        internal static extern uint RunStreaming(short handle, ref uint sampleInterval, ReportedTimeUnits sampleIntervalTimeUnits, uint maxPreTriggerSamples, uint maxPostTriggerSamples, short autoStop, uint downSampleRatio, DownSamplingMode downSampleRatioMode, uint overviewBufferSize);

        [DllImport(DRIVER, EntryPoint = "ps4000aGetStreamingLatestValues")]
        internal static extern uint GetStreamingLatestValues(short handle, ps4000aStreamingReady lpReady, IntPtr pVoid);
    }
}
