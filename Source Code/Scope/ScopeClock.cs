//  Report §3.2: "Stamp every capture block with the same monotonic clock
//  (QueryPerformanceCounter) used by the CAN sniffer ingest path. This is the foundation of
//  the fusion timeline — retrofit is painful, so build it in from the first commit."
//
//  Stopwatch.GetTimestamp() IS QueryPerformanceCounter on Windows, so anything else in TES
//  that stamps with Stopwatch shares this exact clock domain. Correlation to wall time uses
//  a single (qpc, utc) anchor pair taken at type-init so all conversions agree.
// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
using System;
using System.Diagnostics;

namespace TesterPresent.OBD2.Scope
{
    public static class ScopeClock
    {
        private static readonly long _anchorQpc = Stopwatch.GetTimestamp();
        private static readonly DateTime _anchorUtc = DateTime.UtcNow;

        /// <summary>Raw QueryPerformanceCounter ticks (Stopwatch domain).</summary>
        public static long Timestamp() => Stopwatch.GetTimestamp();

        public static double TicksToSeconds(long qpcTicks) => qpcTicks / (double)Stopwatch.Frequency;

        public static long SecondsToTicks(double seconds) => (long)(seconds * Stopwatch.Frequency);

        /// <summary>Best-effort wall-clock for a QPC stamp — for exports and log labels, not for math.</summary>
        public static DateTime ToUtc(long qpcTicks)
            => _anchorUtc + TimeSpan.FromSeconds(TicksToSeconds(qpcTicks - _anchorQpc));
    }
}
