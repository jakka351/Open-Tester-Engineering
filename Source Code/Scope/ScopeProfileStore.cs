using System;
using System.Collections.Generic;
using System.IO;
using Newtonsoft.Json;

namespace TesterPresent.OBD2.Scope
{
    public sealed class ScopeChannelProfile
    {
        public bool Enabled;
        public double RangeVolts;
        public string Coupling;          // "DC" / "AC"
        public double ProbeAttenuation;
    }

    public sealed class ScopeDeviceProfile
    {
        public List<ScopeChannelProfile> Channels = new List<ScopeChannelProfile>();
    }

    public static class ScopeProfileStore
    {
        private static string FilePath => Path.Combine(
            Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),
            "TesterPresent", "ScopeProfiles.json");

        private static Dictionary<string, ScopeDeviceProfile> LoadAll()
        {
            try
            {
                if (File.Exists(FilePath))
                    return JsonConvert.DeserializeObject<Dictionary<string, ScopeDeviceProfile>>(File.ReadAllText(FilePath))
                           ?? new Dictionary<string, ScopeDeviceProfile>();
            }
            catch { /* corrupt profile file → start fresh, never block the tab */ }
            return new Dictionary<string, ScopeDeviceProfile>();
        }

        public static ScopeDeviceProfile Load(string deviceKey)
        {
            if (string.IsNullOrEmpty(deviceKey)) return null;
            var all = LoadAll();
            ScopeDeviceProfile p;
            return all.TryGetValue(deviceKey, out p) ? p : null;
        }

        public static void Save(string deviceKey, ChannelConfig[] channels)
        {
            if (string.IsNullOrEmpty(deviceKey) || channels == null) return;
            try
            {
                var all = LoadAll();
                var profile = new ScopeDeviceProfile();
                foreach (var ch in channels)
                {
                    profile.Channels.Add(new ScopeChannelProfile
                    {
                        Enabled = ch.Enabled,
                        RangeVolts = ch.RangeVolts,
                        Coupling = ch.Coupling == ScopeCoupling.AC ? "AC" : "DC",
                        ProbeAttenuation = ch.ProbeAttenuation,
                    });
                }
                all[deviceKey] = profile;
                Directory.CreateDirectory(Path.GetDirectoryName(FilePath));
                File.WriteAllText(FilePath, JsonConvert.SerializeObject(all, Formatting.Indented));
            }
            catch { /* profile persistence is best-effort */ }
        }

        public static void Apply(ScopeDeviceProfile profile, ChannelConfig[] channels)
        {
            if (profile?.Channels == null || channels == null) return;
            for (int i = 0; i < channels.Length && i < profile.Channels.Count; i++)
            {
                var src = profile.Channels[i];
                channels[i].Enabled = src.Enabled;
                if (src.RangeVolts > 0) channels[i].RangeVolts = src.RangeVolts;
                channels[i].Coupling = string.Equals(src.Coupling, "AC", StringComparison.OrdinalIgnoreCase)
                    ? ScopeCoupling.AC : ScopeCoupling.DC;
                if (src.ProbeAttenuation > 0) channels[i].ProbeAttenuation = src.ProbeAttenuation;
            }
        }
    }
}
