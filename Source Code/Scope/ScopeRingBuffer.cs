// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//  Tester Present Specialist Automotive Solutions — USB Oscilloscope HAL: streaming ring buffer
//  Copyright (c) 2026 Benjamin Jack Leighton. All rights reserved.
//
//  Single-producer / single-consumer sample ring (report §3.2). The producer is the vendor
//  callback or acquisition thread — Write() copies and returns, nothing else runs on the
//  driver's thread. The consumer is the UI refresh timer taking envelope snapshots.
//
//  Lock-free: one Interlocked publish of the write cursor per Write(). SnapshotLatest reads
//  the cursor once and copies backwards; a torn read is impossible (Interlocked.Read) and a
//  concurrent overwrite of the oldest samples during the copy only smears the far-left edge
//  of a scrolling display by one refresh, which is acceptable and unavoidable without locks.
// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
using System;
using System.Threading;

namespace TesterPresent.OBD2.Scope
{
    public sealed class ScopeRingBuffer
    {
        private readonly float[] _buf;
        private readonly int _mask;
        private long _written;   // total samples ever written; publish via Interlocked

        public ScopeRingBuffer(int minCapacity)
        {
            int cap = 1;
            while (cap < minCapacity) cap <<= 1;
            _buf = new float[cap];
            _mask = cap - 1;
        }

        public int Capacity => _buf.Length;

        public long TotalWritten => Interlocked.Read(ref _written);

        /// <summary>Producer side only. Copies <paramref name="count"/> samples then publishes the cursor.</summary>
        public void Write(float[] src, int offset, int count)
        {
            if (count <= 0) return;
            // If a single write exceeds capacity, only the tail can ever be read back — skip the rest.
            if (count > _buf.Length)
            {
                offset += count - _buf.Length;
                Interlocked.Add(ref _written, count - _buf.Length);
                count = _buf.Length;
            }
            long w = Interlocked.Read(ref _written);
            int pos = (int)(w & _mask);
            int first = Math.Min(count, _buf.Length - pos);
            Array.Copy(src, offset, _buf, pos, first);
            if (count > first)
                Array.Copy(src, offset + first, _buf, 0, count - first);
            Interlocked.Add(ref _written, count);
        }

        /// <summary>
        /// Consumer side. Copies the most recent <paramref name="count"/> samples into
        /// <paramref name="dst"/> (oldest first). Returns the number actually available.
        /// </summary>
        public int SnapshotLatest(float[] dst, int count)
        {
            long w = Interlocked.Read(ref _written);
            long avail = Math.Min(w, _buf.Length);
            if (count > avail) count = (int)avail;
            if (count <= 0) return 0;
            long start = w - count;
            int pos = (int)(start & _mask);
            int first = Math.Min(count, _buf.Length - pos);
            Array.Copy(_buf, pos, dst, 0, first);
            if (count > first)
                Array.Copy(_buf, 0, dst, first, count - first);
            return count;
        }
    }
}
