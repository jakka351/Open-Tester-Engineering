//  Report §3.2: "Decimation before UI. Render min/max-decimated envelopes to the display
//  layer; keep full-rate data in the ring buffer for zoom, export, and decode. Never marshal
//  raw sample arrays to the UI thread." Min/max (rather than subsample or average) is the
//  only reduction that cannot hide a glitch narrower than one pixel column.
// ///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
using System;

namespace TesterPresent.OBD2.Scope
{
    /// <summary>One pixel column's worth of envelope.</summary>
    public struct MinMaxPair
    {
        public float Min, Max;
    }

    public static class MinMaxDecimator
    {
        /// <summary>
        /// Reduce <paramref name="count"/> samples (from <paramref name="offset"/>) to
        /// <paramref name="buckets"/> min/max pairs. When there are fewer samples than
        /// buckets the result length equals the sample count (Min == Max per sample).
        /// </summary>
        public static MinMaxPair[] Decimate(float[] samples, int offset, int count, int buckets)
        {
            if (samples == null || count <= 0 || buckets <= 0) return Array.Empty<MinMaxPair>();
            if (count <= buckets)
            {
                var direct = new MinMaxPair[count];
                for (int i = 0; i < count; i++)
                {
                    float v = samples[offset + i];
                    direct[i].Min = v;
                    direct[i].Max = v;
                }
                return direct;
            }

            var result = new MinMaxPair[buckets];
            double samplesPerBucket = count / (double)buckets;
            for (int b = 0; b < buckets; b++)
            {
                int start = offset + (int)(b * samplesPerBucket);
                // Last bucket runs to the true end: buckets×samplesPerBucket can round a
                // fraction below count and silently drop the final sample otherwise.
                int end = b == buckets - 1 ? offset + count : offset + (int)((b + 1) * samplesPerBucket);
                if (end <= start) end = start + 1;
                if (end > offset + count) end = offset + count;
                float mn = samples[start], mx = samples[start];
                for (int i = start + 1; i < end; i++)
                {
                    float v = samples[i];
                    if (v < mn) mn = v;
                    else if (v > mx) mx = v;
                }
                result[b].Min = mn;
                result[b].Max = mx;
            }
            return result;
        }
    }
}
